/**
 * Returns default starter items for any supported tenant ID
 */
export function getDefaultMenuItemsForTenant(tenantId: string): MenuItem[] {
  if (tenantId === 'safari-bistro') {
    return SAFARI_BISTRO_MENU;
  }
  if (tenantId === 'zanzibar-spice') {
    return ZANZIBAR_SPICE_MENU;
  }
  if (tenantId === 'ollis-pizza') {
    return buildOfficialMenuItems('ollis-pizza');
  }
  return getStarterDishesForNewRestaurant(tenantId, 'Restaurant');
}

/**
 * Generates all initial items for all default tenants combined
 */
export function buildAllDefaultTenantMenuItems(): MenuItem[] {
  const ollis = buildOfficialMenuItems('ollis-pizza');
  return [...ollis, ...SAFARI_BISTRO_MENU, ...ZANZIBAR_SPICE_MENU];
}
