export function getTranslation(language: Language | string = 'en', key: string, fallback?: string): string {
  const langKey = language === 'sw' ? 'sw' : 'en';
  const langDict = TRANSLATIONS[langKey] || TRANSLATIONS.en;
  return langDict[key] || TRANSLATIONS.en[key] || fallback || key;
}

export function useAppTranslation(language: Language | string = 'en') {
  const langKey: Language = language === 'sw' ? 'sw' : 'en';
  return {
    t: (key: string, fallback?: string) => getTranslation(langKey, key, fallback),
    lang: langKey,
  };
}

